/**
 * Entry point of the Folkhold World mod.
 */
@Mod(FolkholdWorld.MOD_ID)
public final class FolkholdWorld {
    public static final String MOD_ID = "folkhold_world";
    public static final Logger LOGGER = LogUtils.getLogger();

    public FolkholdWorld(IEventBus modEventBus, ModContainer modContainer) {
        modContainer.registerConfig(ModConfig.Type.SERVER, WorldConfig.SPEC);
        ModBlockFeatures.register(modEventBus);
        ModBlockEntities.register(modEventBus);
        ModEntities.register(modEventBus);
        ModProfessions.register(modEventBus);
        AnimatedVillagers.init();
        ModItems.register(modEventBus);
        ModSounds.register(modEventBus);
        ModStructurePlacements.register(modEventBus);
        ModStructures.register(modEventBus);
        modEventBus.addListener(ModNetwork::register);
        modEventBus.addListener(TestWorldPack::onAddPackFinders);
        NeoForge.EVENT_BUS.addListener(MonsterTargeting::onEntityJoin);
        NeoForge.EVENT_BUS.addListener(VillageRaids::onEntityJoin);
        NeoForge.EVENT_BUS.addListener(VillageRaids::onServerStopped);
        NeoForge.EVENT_BUS.addListener(FriendlyFire::onIncomingDamage);
        NeoForge.EVENT_BUS.addListener(ReputationEvents::onDeath);
        NeoForge.EVENT_BUS.addListener(ReputationEvents::onDamage);
        NeoForge.EVENT_BUS.addListener(FolkholdCommands::onRegisterCommands);
        NeoForge.EVENT_BUS.addListener(VillageRules::onBlockBreak);
        NeoForge.EVENT_BUS.addListener(VillageRules::onRightClickBlock);
        NeoForge.EVENT_BUS.addListener(BankChests::onBlockBreak);
        NeoForge.EVENT_BUS.addListener(BankChests::onLeftClickBlock);
        NeoForge.EVENT_BUS.addListener(BankChests::onExplosion);
        NeoForge.EVENT_BUS.addListener(BankChests::onLoggedOut);
        NeoForge.EVENT_BUS.addListener(Merchants::onEntityInteract);
        NeoForge.EVENT_BUS.addListener(VillageFolk::onEntityInteract);
        NeoForge.EVENT_BUS.addListener(Merchants::onTrade);
        NeoForge.EVENT_BUS.addListener(VillageFolk::onDeath);
        NeoForge.EVENT_BUS.addListener(VillageFolk::onBabySpawn);
        NeoForge.EVENT_BUS.addListener(TerritoryMessages::onPlayerTick);
        NeoForge.EVENT_BUS.addListener(TerritoryMessages::onLoggedOut);
        NeoForge.EVENT_BUS.addListener(TerritoryMessages::onServerStopped);
        NeoForge.EVENT_BUS.addListener(TerritoryMaps::onPlayerTick);
        NeoForge.EVENT_BUS.addListener(TerritoryMaps::onLoggedOut);
        NeoForge.EVENT_BUS.addListener(TerritoryMaps::onServerStopped);
        NeoForge.EVENT_BUS.addListener(Notices::onLoggedOut);
        NeoForge.EVENT_BUS.addListener(Notices::onServerStopped);
        NeoForge.EVENT_BUS.addListener(VillageSpawnProtection::onPositionCheck);
        NeoForge.EVENT_BUS.addListener(VanillaGolems::onPositionCheck);
        NeoForge.EVENT_BUS.addListener((ServerStoppedEvent event) -> VillageHearts.clear());
        NeoForge.EVENT_BUS.addListener(SettlementDiscovery::onServerStarted);
        NeoForge.EVENT_BUS.addListener(SettlementDiscovery::onServerStopped);
        NeoForge.EVENT_BUS.addListener(SettlementDiscovery::onServerTick);
        NeoForge.EVENT_BUS.addListener(VillageDetachments::onEntityJoin);
        NeoForge.EVENT_BUS.addListener(VillageDetachments::onDeath);
        NeoForge.EVENT_BUS.addListener(VillageDetachments::onServerTick);
        NeoForge.EVENT_BUS.addListener(SimulationTicker::onServerTick);
        NeoForge.EVENT_BUS.addListener(SimulationTicker::onServerStopped);
        NeoForge.EVENT_BUS.addListener(CaravanRoutes::onServerStopping);
        NeoForge.EVENT_BUS.addListener(RouteReliefs::onServerStopping);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onChunkLoad);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onChunkUnload);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onBlockPlaced);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onBlockBroken);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onToolModification);
        NeoForge.EVENT_BUS.addListener(RoadNetwork::onServerTick);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onServerTick);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onEntityJoin);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onEntityLeave);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onDeath);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onServerStopping);
        NeoForge.EVENT_BUS.addListener(GroupMaterializer::onServerStopped);
        NeoForge.EVENT_BUS.addListener(GroupBoats::onServerTick);
        NeoForge.EVENT_BUS.addListener(GroupBoats::onEntityJoin);
        NeoForge.EVENT_BUS.addListener(GroupBoats::onAttack);
        NeoForge.EVENT_BUS.addListener(GroupBoats::onInteract);
        NeoForge.EVENT_BUS.addListener(GroupBoats::onServerStopped);
        NeoForge.EVENT_BUS.addListener(CaravanInteractions::onEntityInteract);
        NeoForge.EVENT_BUS.addListener(CaravanInteractions::onTrade);
        NeoForge.EVENT_BUS.addListener(CaravanInteractions::onDamage);
        NeoForge.EVENT_BUS.addListener(CaravanInteractions::onServerStopped);
        NeoForge.EVENT_BUS.addListener(SimulationProfiler::onServerStopped);
        NeoForge.EVENT_BUS.addListener(ConstructionRuns::onServerTick);
        NeoForge.EVENT_BUS.addListener(BuilderSites::onLevelTick);
        NeoForge.EVENT_BUS.addListener(BuilderMaterials::onServerStopped);
        NeoForge.EVENT_BUS.addListener(EventPriority.LOWEST, VillageRepairs::onBlockPlaced);
        NeoForge.EVENT_BUS.addListener(EventPriority.LOWEST, VillageBeds::onBlockPlaced);
        NeoForge.EVENT_BUS.addListener(EventPriority.LOWEST, VillageBeds::onBlockBroken);
        NeoForge.EVENT_BUS.addListener(EventPriority.LOWEST, VillageRepairs::onBlockBroken);
        NeoForge.EVENT_BUS.addListener(VillageRepairs::onServerStopped);
        NeoForge.EVENT_BUS.addListener(ConstructionRuns::onServerStopped);
        NeoForge.EVENT_BUS.addListener(ConstructionCommands::onServerStopped);
        NeoForge.EVENT_BUS.addListener(LevelTables::onAddReloadListener);
        NeoForge.EVENT_BUS.addListener(GarrisonEquipment::onAddReloadListener);
        NeoForge.EVENT_BUS.addListener(EconomyData::onAddReloadListener);
        SimulationTicker.addSystem("economy", Economies::tick);
        SimulationTicker.addSystem("level", SettlementLevels::tick);
        SimulationTicker.addWorldSystem("mobile groups", MobileGroupSystem::tick);
        SimulationTicker.addWorldSystem("trade", VillageTrade::tick);
        SimulationTicker.addWorldSystem("traveling merchants", TravelingMerchants::tick);
        SimulationTicker.addWorldSystem("quests", QuestSystem::tick);
        QuestSystem.addListener(QuestBoards::onQuestEnded);
        NeoForge.EVENT_BUS.addListener(QuestBoards::onEntityInteract);
        NeoForge.EVENT_BUS.addListener(QuestBoards::onLoggedIn);
        QuestBoards.addAcceptListener(Escorts::onAccepted);
        QuestBoards.addEndListener(Escorts::onEnded);
        NeoForge.EVENT_BUS.addListener(Escorts::onServerTick);
        NeoForge.EVENT_BUS.addListener(Escorts::onServerStopped);
        SettlementLevels.addProsperitySource(Economies::prosperity);
        LOGGER.info("{} {} loaded", MOD_ID, modContainer.getModInfo().getVersion());
    }
}
